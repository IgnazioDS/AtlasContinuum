#!/usr/bin/env python3
"""Generate WorldPane's complete Retail zone-reveal table from client DB2 CSVs."""

from __future__ import annotations

import argparse
import csv
import os
from pathlib import Path
import tempfile
import urllib.request


TABLES = ("WorldMapOverlay", "WorldMapOverlayTile")


def fetch(build: str, table: str, destination: Path) -> None:
    url = f"https://wago.tools/db2/{table}/csv?build={build}"
    with urllib.request.urlopen(url, timeout=90) as response, destination.open("wb") as output:
        output.write(response.read())


def rows(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8-sig") as source:
        return list(csv.DictReader(source))


def build_reveal(overlays_path: Path, tiles_path: Path) -> dict[int, dict[str, tuple[int, ...]]]:
    tiles_by_overlay: dict[int, list[dict[str, str]]] = {}
    for tile in rows(tiles_path):
        tiles_by_overlay.setdefault(int(tile["WorldMapOverlayID"]), []).append(tile)

    reveal: dict[int, dict[str, tuple[int, ...]]] = {}
    for overlay in rows(overlays_path):
        width, height = int(overlay["TextureWidth"]), int(overlay["TextureHeight"])
        if width <= 0 or height <= 0:
            continue
        overlay_id = int(overlay["ID"])
        ordered_tiles = sorted(
            tiles_by_overlay.get(overlay_id, ()),
            key=lambda tile: (
                int(tile["LayerIndex"]),
                int(tile["RowIndex"]),
                int(tile["ColIndex"]),
            ),
        )
        file_ids = tuple(int(tile["FileDataID"]) for tile in ordered_tiles if int(tile["FileDataID"]) > 0)
        if not file_ids:
            continue
        art_id = int(overlay["UiMapArtID"])
        key = f'{width}:{height}:{int(overlay["OffsetX"])}:{int(overlay["OffsetY"])}'
        # Some phased/conditioned overlays intentionally occupy one rectangle.
        # DB2 order matches the client generator's precedence; the last row is
        # the same deterministic choice used by the historical reveal table.
        reveal.setdefault(art_id, {})[key] = file_ids
    return reveal


def lua_source(build: str, reveal: dict[int, dict[str, tuple[int, ...]]]) -> str:
    lines = [
        "-- Explored-area pieces per zone art: [UiMapArtID] = { [\"w:h:x:y\"] = \"fileIDs, row-major\" }.",
        f"-- Generated by scripts/build_reveal.py from the game's tables (build {build}); regenerate rather than edit.",
        "",
        "local _, ns = ...",
        "",
        "ns.MapReveal = {",
    ]
    for art_id in sorted(reveal):
        entries = []
        for key in sorted(reveal[art_id]):
            ids = ", ".join(str(file_id) for file_id in reveal[art_id][key])
            entries.append(f'["{key}"] = "{ids}"')
        lines.append(f"\t[{art_id}] = {{{', '.join(entries)}}},")
    lines.extend(("}", ""))
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--build", default="12.1.5.70448")
    parser.add_argument("--overlay-csv", type=Path)
    parser.add_argument("--tile-csv", type=Path)
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).resolve().parents[1] / "WorldPane/Data/Retail/Reveal.lua",
    )
    args = parser.parse_args()

    with tempfile.TemporaryDirectory(prefix="worldpane-reveal-") as temporary:
        work = Path(temporary)
        overlays = args.overlay_csv or work / f"{TABLES[0]}.csv"
        tiles = args.tile_csv or work / f"{TABLES[1]}.csv"
        if args.overlay_csv is None:
            fetch(args.build, TABLES[0], overlays)
        if args.tile_csv is None:
            fetch(args.build, TABLES[1], tiles)

        source = lua_source(args.build, build_reveal(overlays, tiles))
        args.output.parent.mkdir(parents=True, exist_ok=True)
        temporary_output = args.output.with_suffix(args.output.suffix + ".tmp")
        temporary_output.write_text(source, encoding="utf-8", newline="\n")
        os.replace(temporary_output, args.output)
        print(f"wrote {args.output} ({source.count(chr(10)) + 1} lines)")


if __name__ == "__main__":
    main()
